#!/usr/bin/env node
// @ts-check
/**
 * `docs/TYPECHECK-WORKLIST.md`, generated from the compiler.
 *
 * The file list was accurate and the **counts were not**: 362 claimed against
 * 428 actual, and one file listed at 0 errors that had 55 — the largest
 * offender in the tree, presented as ready to adopt. A hand-maintained count
 * beside a generated list is worse than no count, because it reads as
 * measured.
 *
 * So it is measured. This runs the compiler twice — once as the build runs it,
 * once with `checkJs` on for the whole tree — and the difference is what each
 * unchecked file would cost to adopt. `tests/structure.test.js` fails the
 * build when the document and the tree disagree.
 *
 *   npm run docs:typecheck-worklist
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DOC = path.join(ROOT, 'docs', 'TYPECHECK-WORKLIST.md');

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (p.endsWith('.js')) out.push(p);
  }
  return out;
};

const rel = f => path.relative(ROOT, f).split(path.sep).join('/');

/** Every file under src/, split by whether it carries the pragma. */
function survey() {
  const files = walk(path.join(ROOT, 'src'));
  const checked = [], unchecked = [];
  for (const f of files) {
    (/^\/\/ @ts-check/m.test(fs.readFileSync(f, 'utf8')) ? checked : unchecked).push(rel(f));
  }
  return { checked: checked.sort(), unchecked: unchecked.sort() };
}

/**
 * Errors per file with `checkJs` on for the whole tree. That is what a file
 * would cost to adopt, which is the only figure this document is for.
 */
function errorsByFile() {
  const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'jsconfig.json'), 'utf8'));
  cfg.compilerOptions.checkJs = true;
  const probe = path.join(ROOT, 'jsconfig.worklist.json');
  fs.writeFileSync(probe, JSON.stringify(cfg, null, 2));
  let out = '';
  try {
    execFileSync('npx', ['tsc', '-p', probe], { cwd: ROOT, encoding: 'utf8' });
  } catch (thrown) {
    /* tsc exits non-zero when it finds errors, and the report is on stdout. */
    const e = /** @type {any} */ (thrown);
    out = String((e && e.stdout) || '');
  } finally {
    fs.unlinkSync(probe);
  }
  /** @type {Record<string, number>} */
  const counts = {};
  for (const line of out.split('\n')) {
    const m = line.match(/^(.+?)\(\d+,\d+\): error TS/);
    if (!m) continue;
    const f = m[1].split(path.sep).join('/');
    counts[f] = (counts[f] || 0) + 1;
  }
  return counts;
}

function render({ checked, unchecked }, counts) {
  const rows = unchecked.map(f => ({ f, n: counts[f] || 0 }))
    .sort((a, b) => b.n - a.n || a.f.localeCompare(b.f));
  const total = rows.reduce((n, r) => n + r.n, 0);
  const clean = rows.filter(r => r.n === 0);

  return `# Type-check worklist

**Generated by \`npm run docs:typecheck-worklist\`. Do not edit.**
\`tests/structure.test.js\` fails the build when this document and the tree
disagree — a list whose counts are wrong reads as measured when it is not.

\`npm run typecheck\` runs the TypeScript compiler over the JavaScript tree
with \`checkJs\` off globally and on per file: a file carrying \`// @ts-check\`
is checked with JSDoc as its types. Every file under \`src/platform\`,
\`src/shared\`, the composition roots and the Netlify functions carries it; so
does every clean file elsewhere. A file joins the check the day its errors are
fixed, never by adding the pragma over them.

The compiler runs at **\`strict: true\` with \`noImplicitAny\` off** — so null
safety, \`this\`, unused locals, unreachable returns and catch narrowing are
all enforced, and only the missing-annotation class is not. Adopting
\`noImplicitAny\` is the remaining step and is measured below.

Checked: **${checked.length}** files. Remaining: **${rows.length}** (${total} errors under the
settings above, with \`checkJs\` on for the whole tree).

The per-file count is what that file raises when **every** file is checked.
Adopting one on its own can differ by a little, because a checked dependency
infers differently from an unchecked one — so treat the figure as the size of
the job, not as a contract.

${clean.length ? `**${clean.length} of them raise no errors at all** and can be adopted by adding the
pragma and nothing else.
` : ''}
| File | Errors to fix before it joins |
|---|---|
${rows.map(r => `| \`${r.f}\` | ${r.n} |`).join('\n')}
`;
}

const s = survey();
const counts = errorsByFile();
fs.writeFileSync(DOC, render(s, counts));
console.log(`[typecheck-worklist] ${s.checked.length} checked, ${s.unchecked.length} remaining → docs/TYPECHECK-WORKLIST.md`);
