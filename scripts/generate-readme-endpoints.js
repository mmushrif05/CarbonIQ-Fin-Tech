#!/usr/bin/env node
// @ts-check
/**
 * Rebuild the README's endpoint table from docs/openapi.json.
 *
 * The hand-written table listed about 26 of 163 operations and five of those
 * returned 404 — `POST /v1/score`, `GET /v1/taxonomy`, `POST /v1/pcaf`,
 * `POST /v1/covenant` and `POST /v1/webhook` are all project-scoped or plural
 * in the router. A reader following the README got a 404 from the first four
 * things they tried, which is the worst possible first hour.
 *
 * The document is generated from the running router, so this is generated
 * from that.
 *
 *   npm run docs:readme
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const README = path.join(ROOT, 'README.md');
const doc = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs', 'openapi.json'), 'utf8'));

/**
 * Which section of the surface a path belongs to, in the order a reader meets
 * them.
 * @type {Array<[string, (p: string) => boolean]>}
 */
const GROUPS = [
  ['Getting in', p => p.startsWith('/v1/auth') || p === '/health' || p === '/v1' || p.startsWith('/v1/ui-config')],
  ['PCAF Part C — insurance-associated emissions', p => p.startsWith('/v1/pcaf/part-c') || p.startsWith('/v1/partc')],
  ['PCAF Part A — financed emissions', p => p.startsWith('/v1/pcaf/part-a')],
  ['The GCF pipeline', p => p.startsWith('/v1/gcf')],
  ['The capital book and the Fund Desk', p => p.startsWith('/v1/capital') || p.startsWith('/v1/desk')],
  ['Baselines', p => p.startsWith('/v1/baselines')],
  ['Lending — assessment, scoring, covenants', p => /^\/v1\/(assess|extract|projects|portfolio|reports|agent|supervisor|webhooks|assurance)/.test(p)],
  ['Sri Lanka — taxonomy, NDC and carbon pricing', p => p.startsWith('/v1/ndc-sdg') || p.startsWith('/v1/carbon-pricing')],
  ['Operating the service', p => p.startsWith('/v1/jobs') || p.startsWith('/v1/metrics') || p.startsWith('/v1/openapi')],
];

const rows = [];
for (const [name, match] of GROUPS) {
  const paths = Object.keys(doc.paths).filter(match).sort();
  if (!paths.length) continue;
  rows.push({ heading: name, lines: paths.flatMap(p =>
    Object.entries(doc.paths[p])
      .filter(([m]) => ['get', 'post', 'put', 'patch', 'delete'].includes(m))
      .map(([method, op]) => ({
        method: method.toUpperCase(),
        path: p,
        summary: op.summary || '',
        scope: (op['x-scope'] || op['x-required-scope'] || '') || '',
      }))) });
}

const seen = new Set(rows.flatMap(r => r.lines.map(l => `${l.method} ${l.path}`)));
const total = Object.keys(doc.paths).reduce((n, p) =>
  n + Object.keys(doc.paths[p]).filter(m => ['get', 'post', 'put', 'patch', 'delete'].includes(m)).length, 0);
if (seen.size !== total) {
  const all = [];
  for (const p of Object.keys(doc.paths)) {
    for (const m of Object.keys(doc.paths[p])) {
      if (['get', 'post', 'put', 'patch', 'delete'].includes(m) && !seen.has(`${m.toUpperCase()} ${p}`)) all.push(`${m.toUpperCase()} ${p}`);
    }
  }
  process.stderr.write(`Ungrouped operations (add a group to scripts/generate-readme-endpoints.js):\n  ${all.join('\n  ')}\n`);
  process.exitCode = 1;
}

let table = `_${total} operations across ${Object.keys(doc.paths).length} paths. Generated from \`docs/openapi.json\`, which is itself generated from the router — so a route that is not here does not exist. \`docs/API-SCOPES.md\` has the scope each one requires._\n`;
for (const g of rows) {
  table += `\n### ${g.heading}\n\n| Method | Path | What it does |\n|---|---|---|\n`;
  for (const l of g.lines) table += `| \`${l.method}\` | \`${l.path}\` | ${l.summary.replace(/\|/g, '\\|')} |\n`;
}

const begin = '<!-- BEGIN ENDPOINTS — generated by npm run docs:readme -->';
const end = '<!-- END ENDPOINTS -->';
const text = fs.readFileSync(README, 'utf8');
const from = text.indexOf(begin);
const to = text.indexOf(end);
if (from === -1 || to === -1) throw new Error('README.md has no ENDPOINTS block');
fs.writeFileSync(README, `${text.slice(0, from + begin.length)}\n${table}\n${text.slice(to)}`);
process.stderr.write(`Wrote the README endpoint table — ${total} operations\n`);
