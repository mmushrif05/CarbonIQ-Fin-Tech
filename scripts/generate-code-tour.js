#!/usr/bin/env node
// @ts-check
/**
 * Rebuild the generated blocks of docs/CODE-TOUR.md.
 *
 * Two of them cannot be maintained by hand and stay true: the entity-relation
 * diagram, which is the shape of `src/platform/database/collections.js`, and
 * the module map, which is the shape of `src/`. A hand-drawn diagram of either
 * is wrong within a month and is believed for a year.
 *
 * Everything outside the markers is prose and is written by a person.
 *
 *   npm run docs:code-tour
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'CODE-TOUR.md');

const { COLLECTIONS } = require('../src/platform/database/collections');

/** Replace what sits between `<!-- BEGIN x -->` and `<!-- END x -->`. */
function replaceBlock(text, name, body) {
  const begin = `<!-- BEGIN ${name} — generated by npm run docs:code-tour -->`;
  const end = `<!-- END ${name} -->`;
  const from = text.indexOf(begin);
  const to = text.indexOf(end);
  if (from === -1 || to === -1) throw new Error(`docs/CODE-TOUR.md has no ${name} block`);
  return `${text.slice(0, from + begin.length)}\n${body}\n${text.slice(to)}`;
}

/** The tables, and the foreign keys between them. */
function erd() {
  const lines = ['```mermaid', 'erDiagram'];
  const entity = name => COLLECTIONS[name].table;

  for (const [name, def] of Object.entries(COLLECTIONS)) {
    const fields = ['string id PK', 'string owner_org_id', 'jsonb record'];
    for (const [prop, column] of Object.entries(def.keys || {})) {
      fields.push(`string ${column} "${prop}"`);
    }
    lines.push(`  ${entity(name)} {`);
    for (const f of fields) lines.push(`    ${f}`);
    lines.push('  }');
  }

  for (const [name, def] of Object.entries(COLLECTIONS)) {
    for (const parent of def.dependsOn || []) {
      /* ON DELETE RESTRICT everywhere: a parent with children cannot be
         deleted, and the refusal names what is attached. */
      lines.push(`  ${entity(parent)} ||--o{ ${entity(name)} : "restrict"`);
    }
  }
  lines.push('```');
  return lines.join('\n');
}

/** What is under `src/`, one line per directory that holds code. */
function moduleMap() {
  const rows = [];
  const walk = (dir, depth) => {
    const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
    const files = entries.filter(e => e.isFile() && e.name.endsWith('.js'));
    const dirs = entries.filter(e => e.isDirectory());
    const rel = path.relative(path.join(ROOT, 'src'), dir).split(path.sep).join('/') || '.';
    if (files.length) {
      const lines = files.reduce((n, f) => n + fs.readFileSync(path.join(dir, f.name), 'utf8').split('\n').length, 0);
      rows.push({ rel, depth, files: files.length, lines });
    }
    for (const d of dirs) walk(path.join(dir, d.name), depth + 1);
  };
  walk(path.join(ROOT, 'src'), 0);

  let out = '| Directory | Files | Lines |\n|---|---:|---:|\n';
  for (const r of rows) {
    const indent = '  '.repeat(r.depth);
    out += `| ${indent}\`${r.rel === '.' ? 'src/' : `src/${r.rel}/`}\` | ${r.files} | ${r.lines.toLocaleString('en-US')} |\n`;
  }
  const total = rows.reduce((n, r) => n + r.lines, 0);
  out += `| **total** | **${rows.reduce((n, r) => n + r.files, 0)}** | **${total.toLocaleString('en-US')}** |\n`;
  return out;
}

let text = fs.readFileSync(OUT, 'utf8');
text = replaceBlock(text, 'ERD', erd());
text = replaceBlock(text, 'MODULE-MAP', moduleMap());
fs.writeFileSync(OUT, text);
process.stderr.write(`Wrote docs/CODE-TOUR.md — ${Object.keys(COLLECTIONS).length} tables\n`);
